#!/usr/bin/env python3
"""
build_executed_route_viz.py — Interactive visualization of actual executed vehicle routes
==========================================================================================
Reads executed_routes.json (generated by ExecutedRouteRecorder) and produces a
self-contained HTML page with:
  - Vehicle selector with route statistics
  - Timeline view with detailed node cards (arrive/leave, deliveries, pickups, carrying)
  - Route summary and statistics

Usage:
    python build_executed_route_viz.py <executed_routes.json> [output.html]
    
    python build_executed_route_viz.py visualization_output/instance_1/executed_routes.json
    python build_executed_route_viz.py visualization_output/instance_1/executed_routes.json my_viz.html
"""

