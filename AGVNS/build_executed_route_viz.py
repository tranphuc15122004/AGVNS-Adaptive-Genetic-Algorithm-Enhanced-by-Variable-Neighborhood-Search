def main():
    """Main entry point."""
    if len(sys.argv) < 2:
        print(__doc__)
        print("ERROR: Please provide the path to executed_routes.json")
        sys.exit(1)

    input_path = sys.argv[1]
    if not os.path.exists(input_path):
        print(f"ERROR: File not found: {input_path}")
        sys.exit(1)

    # Default output path: same directory as input
    if len(sys.argv) >= 3:
        output_path = sys.argv[2]
    else:
        output_dir = os.path.dirname(input_path)
        output_path = os.path.join(output_dir, 'executed_routes.html')

    # Load data
    print(f"Loading: {input_path}")
    with open(input_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    instance = data.get('instance', 'Unknown')
    vehicles = data.get('vehicles', {})
    total_nodes = sum(v['total_nodes'] for v in vehicles.values())

    print(f"  Instance: {instance}")
    print(f"  Vehicles: {len(vehicles)}")
    print(f"  Total executed nodes: {total_nodes}")

    # Generate HTML
    print(f"Generating HTML...")
    html = generate_html(data)

    # Write output
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(html)

    print(f"✅ Output: {output_path}")
    print(f"   Open in browser: file:///{os.path.abspath(output_path).replace(os.sep, '/')}")


if __name__ == '__main__':
    main()
